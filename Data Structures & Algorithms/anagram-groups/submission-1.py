class Solution:
    def groupAnagrams(self, strs: List[str]) -> List[List[str]]:
        word_map = dict()
        for wrd in strs:
            sorted_wrd = ''.join(sorted(wrd))
            if sorted_wrd not in word_map:
                word_map[sorted_wrd] = [wrd]
            else:
                word_map[sorted_wrd].append(wrd)
        return list(word_map.values())




































































































































































































































































