class Solution:
    def groupAnagrams(self, strs: List[str]) -> List[List[str]]:
        word_map = dict()
        for wrd in strs:
            if ''.join(sorted(wrd)) not in word_map:
                word_map[''.join(sorted(wrd))] = [wrd]
            else:
                word_map[''.join(sorted(wrd))].append(wrd)
        return list(word_map.values())




































































































































































































































































